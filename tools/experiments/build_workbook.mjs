// Use a supplied artifact-tool entry point; never install a global dependency.
import fs from 'node:fs/promises';
import path from 'node:path';
const [entry, output] = process.argv.slice(2);
if (!entry || !output) throw new Error('Usage: node build_workbook.mjs artifact-tool-entry output-dir');
const {Workbook, SpreadsheetFile} = await import(entry);
const data = JSON.parse(await fs.readFile(path.join(output, 'entity.json'), 'utf8'));
const wb = Workbook.create();
const sheet = wb.worksheets.add('Entity');
sheet.showGridLines = false;
sheet.getRange('A2').values = [[data.title]];
sheet.getRange('A3').values = [[data.entity]];
sheet.getRange('A4').values = [['合成試料・ローカル変換試験 2026-09-26']];
sheet.getRange('A6:G9').values = [data.headers, ...data.rows];
sheet.getRange('A11').values = [['属性数']];
sheet.getRange('B11').formulas = [['=COUNT(A7:A9)']];
sheet.getRange('A13').values = [[data.provenance]];
sheet.getRange('A14').values = [['元テンプレート: '+data.template]];
sheet.getRange('A15').values = [['逆生成元: build_document.py / Invoice']];
sheet.getRange('A16').values = [['元コードSHA256: '+data.source_sha256]];
sheet.getRange('A17').values = [['空欄を保持。実Microsoft Excelでの表示・操作は未確認。']];
sheet.getRange('A2:G17').format.font = {name:'Arial Unicode MS',size:10,color:'#17202A'};
sheet.getRange('A2').format.font = {name:'Arial Unicode MS',size:14,bold:true};
sheet.getRange('A6:G6').format = {fill:'#23384D',font:{name:'Arial Unicode MS',size:10,bold:true,color:'#FFFFFF'},horizontalAlignment:'center',verticalAlignment:'center'};
sheet.getRange('A6:G9').format.verticalAlignment = 'center';
sheet.getRange('A7:A9').setNumberFormat('0');
sheet.getRange('B7:G9').setNumberFormat('@');
sheet.getRange('B11').setNumberFormat('0');
sheet.getRange('A7:G9').format.wrapText = true;
const widths = [45,150,130,50,55,450,135];
for(let i=0;i<7;i++) sheet.getRangeByIndexes(5,i,4,1).format.columnWidthPx=widths[i];
sheet.getRange('A6:G8').format.rowHeightPx = 32;
sheet.getRange('A9:G9').format.rowHeightPx = 100;
sheet.getRange('A13:G17').format.rowHeightPx = 24;
wb.recalculate();
if(sheet.getRange('B11').values[0][0] !== 3) throw new Error('Count mismatch');
sheet.getRange('A9').values = [[null]];
wb.recalculate();
if(sheet.getRange('B11').values[0][0] !== 2) throw new Error('Count failed input edit');
sheet.getRange('A9').values = [[3]];
wb.recalculate();
const got = sheet.getRange('A6:G9').values;
if(JSON.stringify(got.map(row=>row.map(v=>v ?? ''))) !== JSON.stringify([data.headers,...data.rows])) throw new Error('Cell mismatch');
await fs.writeFile(path.join(output,'xlsx-inspect.json'), JSON.stringify(await wb.inspect({kind:'region',sheetId:'Entity',range:'A6:G11',maxChars:4000}),null,2));
const image = await wb.render({sheetName:'Entity',range:'A1:G18',scale:1.5,format:'png'});
await fs.writeFile(path.join(output,'entity-sheet.png'),new Uint8Array(await image.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(wb)).save(path.join(output,'entity.xlsx'));
console.log('XLSX: table matched; COUNT 3 -> 2 -> 3 verified; rendered Entity');
